export const exercises: Exercise[] = catalog.flatMap(
  ([muscleGroup, names], g) =>
    names.map((name, i) => ({
      id: `system-${g}-${i}`,
      name,
      muscleGroup,
      exerciseType:
        name === "Планка"
          ? "duration"
          : bodyweight.includes(name)
            ? "bodyweight"
            : "weighted",
      isCustom: false,
      isArchived: false,
    })),
);
const ids = (names: string[]) =>
  names.map((n) => exercises.find((e) => e.name === n)!.id);
